/** AntD theme for the isolated /design-lab preview only. */
export function getVzLabAntTheme(dark: boolean): ThemeConfig {
    const c = dark ? palette.dark : palette.light;
    return {
        algorithm: dark ? antdTheme.darkAlgorithm : antdTheme.defaultAlgorithm,
        cssVar: { key: dark ? "vzl-dark" : "vzl-light" },
        token: {
            colorPrimary: c.brand,
            colorLink: c.brandText,
            colorInfo: c.info,
            colorSuccess: c.success,
            colorWarning: c.warning,
            colorError: c.error,
            colorBgBase: c.bg,
            colorBgLayout: c.bg,
            colorBgContainer: c.s2,
            colorBgElevated: c.elevated,
            colorBorder: c.control,
            colorBorderSecondary: c.border,
            colorSplit: c.border,
            colorText: c.text,
            colorTextSecondary: c.text2,
            colorTextTertiary: c.text3,
            colorTextPlaceholder: c.text3,
            colorFillTertiary: c.hover,
            borderRadius: 12,
            borderRadiusSM: 8,
            borderRadiusLG: 16,
            controlHeight: 40,
            controlHeightSM: 32,
            controlHeightLG: 48,
            fontFamily: '-apple-system, BlinkMacSystemFont, "SF Pro Text", "PingFang SC", "Microsoft YaHei", system-ui, sans-serif',
            motionEaseOut: "cubic-bezier(0.2, 0.8, 0.2, 1)",
        },
        components: {
            Select: { optionSelectedBg: dark ? "rgba(124,108,255,0.18)" : "rgba(95,75,255,0.1)", optionActiveBg: c.hover },
            Segmented: { trackBg: c.s1, itemSelectedBg: c.s3, itemColor: c.text2, itemHoverColor: c.text, itemSelectedColor: c.text },
            Tabs: { itemColor: c.text2, itemHoverColor: c.text, itemSelectedColor: c.text, itemActiveColor: c.text },
            Tooltip: { colorBgSpotlight: c.tip },
            Modal: { borderRadiusLG: 24, contentBg: c.s1, headerBg: "transparent", titleFontSize: 18 },
            Popover: { borderRadiusLG: 18 },
        },
    };
}
